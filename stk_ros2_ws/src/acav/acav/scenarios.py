"""Which scenario a run used, and whether the twin can run it (P10c).

The reference scenario (config/acav_scenario.yaml) is the one the twin
reads -- its MATLAB YAML reader always opens that file -- and the one
every record so far names. Generated scenarios (acav.scenario_generator)
live in config/scenarios/generated and differ from it only in their
targets and the missing ground station.

- :func:`known_scenarios`: the reference, the generated files and any
  extra file, by digest;
- :func:`scenario_of`: a record's scenario among them (legacy digests
  mapped, run_record.LEGACY_SCENARIO_DIGESTS);
- :func:`scenario_origin` / :func:`scenario_provenance`: seed and
  generator version from a generated file's header;
- :func:`twin_parameter_differences`: the shared sections a scenario
  does not have in common with the reference -- a run on it would give
  the twin (reading the reference) other parameters than the scheduler.
"""

from __future__ import annotations

import glob
import os
import re
from typing import Dict, Iterable, List, Optional, Tuple

from acav.run_record import (
    LEGACY_SCENARIO_DIGESTS,
    RunRecord,
    ScenarioTargets,
    scenario_targets,
)
from acav.spec import AcavSpec

#: The sections the twin takes from the reference, so a scenario must
#: have them unchanged.
SHARED_SECTIONS = ("scenario", "spacecraft", "sensor", "actuators",
                   "pointing", "scheduling", "bridge")

GENERATED_DIR = os.path.join(os.path.dirname(AcavSpec.default_path()),
                             "scenarios", "generated")

_ORIGIN = re.compile(r"^# GENERATED by acav\.scenario_generator, generator "
                     r"version (\S+), from seed (-?\d+)\.")


#: The generated scenarios relative to the workspace (the current
#: directory): through `ros2 run` GENERATED_DIR is the installed copy,
#: which has none.
WORKSPACE_GENERATED_DIR = os.path.join("src", "acav", "config", "scenarios",
                                       "generated")


def scenario_dirs(scenario_dir: str = "") -> List[str]:
    """Where generated scenarios are looked for, absolute, in order."""
    dirs = [scenario_dir, WORKSPACE_GENERATED_DIR, GENERATED_DIR]
    out: List[str] = []
    for directory in dirs:
        if directory and os.path.abspath(directory) not in out:
            out.append(os.path.abspath(directory))
    return out


def known_scenarios(extra_paths: Iterable[str] = (), scenario_dir: str = ""
                    ) -> Dict[str, ScenarioTargets]:
    """digest -> ScenarioTargets for the reference, the generated files
    (:func:`scenario_dirs`) and ``extra_paths``."""
    paths = [AcavSpec.locate()]
    for directory in scenario_dirs(scenario_dir):
        paths += sorted(glob.glob(os.path.join(directory, "*.yaml")))
    paths += [p for p in extra_paths if p]
    known: Dict[str, ScenarioTargets] = {}
    for path in paths:
        scenario = scenario_targets(path)
        known.setdefault(scenario.sha256, scenario)
    return known


def scenario_of(record: RunRecord, known: Dict[str, ScenarioTargets]
                ) -> Optional[ScenarioTargets]:
    """The record's scenario among ``known``, or None."""
    named = record.provenance.scenario_sha256
    return known.get(LEGACY_SCENARIO_DIGESTS.get(named, named))


def scenario_origin(path: str) -> Tuple[Optional[int], str]:
    """(seed, generator version) of a generated file; (None, "") else."""
    with open(path, encoding="utf-8") as handle:
        first = handle.readline().rstrip("\r\n")
    match = _ORIGIN.match(first)
    if not match:
        return None, ""
    return int(match.group(2)), match.group(1)


def scenario_provenance(path: str) -> dict:
    """The provenance fields a record carries for scenario ``path``."""
    from acav.run_record import scenario_digest

    seed, version = scenario_origin(path)
    return {"scenario_sha256": scenario_digest(path), "scenario_seed": seed,
            "scenario_generator_version": version}


def twin_parameter_differences(path: str,
                               reference_path: str = "") -> List[str]:
    """SHARED_SECTIONS that differ between ``path`` and the reference."""
    scenario = AcavSpec.load(path).raw
    reference = AcavSpec.load(reference_path or None).raw
    return [section for section in SHARED_SECTIONS
            if scenario.get(section) != reference.get(section)]
