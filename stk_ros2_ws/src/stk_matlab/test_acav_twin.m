function results = test_acav_twin(fixturePath)
%TEST_ACAV_TWIN Check the MATLAB twin against the Python reference.
%
%   test_acav_twin()                     % uses the shipped fixtures
%   results = test_acav_twin(path)       % explicit fixture file
%
% The Simulink twin is a transcription of acav/twin_reference.py, and a
% transcription is exactly the work that produces a sign error somewhere
% in three hundred lines of quaternion algebra. Such an error does not
% crash. It flies the twin smoothly to a slightly -- or completely --
% wrong attitude, STK reports no access, and the result reads as a
% control-design finding.
%
% So the two implementations are held together by data. This replays
% fixtures generated by the reference and asserts agreement to 1e-9,
% far tighter than anything the study measures. One transcription error
% was already caught this way before shipping: adcs.quat.align had a
% transposed rotation matrix, which produces a valid attitude pointing
% roughly 180 deg away from the target.
%
% Written in the same spirit as verify_acav_scenario.py: every check
% runs, nothing stops at the first failure, and the summary says what is
% wrong rather than merely that something is.
%
% Exit: prints a summary and returns a struct array. results(k).status
% is "pass" or "FAIL".

    if nargin < 1 || isempty(fixturePath)
        here = fileparts(mfilename('fullpath'));
        fixturePath = fullfile(fileparts(here), 'acav', 'config', ...
            'twin_fixtures.json');
    end
    if ~isfile(fixturePath)
        error('test_acav_twin:NoFixtures', ...
            ['fixtures not found at %s.\nGenerate them with:\n' ...
             '  python src/acav/scripts/export_twin_fixtures.py'], ...
            fixturePath);
    end

    fx = jsondecode(fileread(fixturePath));
    EXPECTED_VERSION = 1;
    if fx.version ~= EXPECTED_VERSION
        error('test_acav_twin:StaleFixtures', ...
            ['fixture version %d, this test expects %d. Regenerate the ' ...
             'fixtures, and read the diff -- a change in an expected ' ...
             'value is a change in what the twin is required to do.'], ...
            fx.version, EXPECTED_VERSION);
    end

    fprintf('ACAV twin cross-check against the Python reference\n');
    fprintf('%s\n', repmat('=', 1, 64));

    results = struct('name', {}, 'status', {}, 'detail', {});
    tol = 1e-9;

    results = quatAlgebra(results, fx, tol);
    results = attitudes(results, fx, tol);
    results = wheelCases(results, fx, tol);
    results = dynamicsCases(results, fx, tol);
    results = profileCases(results, fx, tol);
    results = controllerCases(results, fx, tol);
    results = modeCases(results, fx);
    results = closedLoopCases(results, fx);

    fprintf('%s\n', repmat('-', 1, 64));
    failed = sum(strcmp({results.status}, 'FAIL'));
    fprintf('%d checks: %d passed, %d failed\n', numel(results), ...
        numel(results) - failed, failed);
    for k = 1:numel(results)
        if strcmp(results(k).status, 'FAIL')
            fprintf('  FAILED: %s\n', results(k).name);
        end
    end
    if failed == 0
        fprintf(['\nThe MATLAB twin reproduces the reference. Note this ' ...
                 'says nothing\nabout STK: run ' ...
                 'verify_acav_scenario.py for that.\n']);
    end
end

% -----------------------------------------------------------------------

function results = record(results, name, ok, detail)
    entry = struct('name', name, 'status', "pass", 'detail', detail);
    if ~ok
        entry.status = "FAIL";
    end
    results(end+1) = entry; %#ok<AGROW>
    marker = "  ok  ";
    if ~ok
        marker = " FAIL ";
    end
    fprintf('[%s] %s\n', marker, name);
    if ~ok && strlength(detail) > 0
        fprintf('           %s\n', detail);
    end
end

function [ok, detail] = compareVec(actual, expected, tol)
    actual = actual(:).';
    expected = expected(:).';
    if numel(actual) ~= numel(expected)
        ok = false;
        detail = sprintf('length %d, expected %d', numel(actual), ...
            numel(expected));
        return
    end
    worst = max(abs(actual - expected));
    ok = worst <= tol;
    detail = sprintf('worst |diff| = %.3e (tol %.1e)\n           got      %s\n           expected %s', ...
        worst, tol, mat2str(actual, 12), mat2str(expected, 12));
end

function results = quatAlgebra(results, fx, tol)
    for k = 1:numel(fx.quaternion_algebra)
        c = fx.quaternion_algebra(k);
        switch c.name
            case 'multiply'
                got = adcs.quat.multiply(c.a.', c.b.');
                [ok, d] = compareVec(got, c.expected, tol);
            case 'rotate_inertial_x_into_body_after_90deg_yaw'
                got = adcs.quat.toBody(c.a.', c.vector.');
                [ok, d] = compareVec(got, c.expected(1:3), tol);
            case 'error_quaternion_is_body_referenced'
                got = adcs.quat.error(c.a.', c.b.');
                [ok, d] = compareVec(got, c.expected, tol);
            case 'boresight_error_ignores_roll'
                got = adcs.quat.boresightError(c.a.', c.b.', [0 0 1]);
                [ok, d] = compareVec(got, c.expected_scalar, tol);
            otherwise
                ok = false; d = 'unknown case';
        end
        results = record(results, ['quat: ' c.name], ok, d);
    end
end

function results = attitudes(results, fx, tol)
    boresight = fx.config.boresight_body.';
    for k = 1:numel(fx.attitude_construction)
        c = fx.attitude_construction(k);
        if strcmp(c.name, 'nadir')
            nadir = -c.position.' / norm(c.position);
            got = adcs.quat.align(boresight, nadir, [1 0 0], c.velocity.');
        else
            los = c.target.' - c.position.';
            got = adcs.quat.align(boresight, los / norm(los), ...
                [1 0 0], c.velocity.');
        end
        % Compare as attitudes, not as component tuples: q and -q are
        % the same attitude and Shepperd's branch selection may pick
        % either sign.
        angle = adcs.quat.pointingError(got, c.expected.');
        [ok, d] = compareVec(angle, 0, 1e-9);
        results = record(results, ['attitude: ' c.name], ok, d);
    end
end

function results = wheelCases(results, fx, tol)
    cfgFx = fx.config;
    for k = 1:numel(fx.wheels)
        c = fx.wheels(k);
        [delivered, momentum, saturated] = adcs.wheels( ...
            c.torque_Nm.', c.dt, c.initial_momentum_Nms.', ...
            cfgFx.max_torque_Nm, cfgFx.momentum_capacity_Nms, ...
            c.health.');
        [okA, dA] = compareVec(delivered, c.expected_delivered_Nm, tol);
        [okB, dB] = compareVec(momentum, c.expected_momentum_Nms, tol);
        okC = saturated == c.expected_saturated;
        detail = dA;
        if ~okB
            detail = dB;
        elseif ~okC
            detail = sprintf('saturated flag %d, expected %d', ...
                saturated, c.expected_saturated);
        end
        results = record(results, ['wheels: ' c.name], ...
            okA && okB && okC, detail);
    end
end

function results = dynamicsCases(results, fx, tol)
    inertia = fx.config.inertia_kg_m2.';
    for k = 1:numel(fx.dynamics)
        c = fx.dynamics(k);
        q = [0 0 0 1];
        w = c.initial_rate_rad_s.';
        for step = 1:c.steps
            [q, w] = adcs.rigid_body_step(q, w, c.torque_Nm.', ...
                c.wheel_momentum_Nms.', inertia, c.dt);
        end
        angle = adcs.quat.pointingError(q, c.expected_quaternion.');
        [okA, dA] = compareVec(angle, 0, 1e-8);
        [okB, dB] = compareVec(w, c.expected_rate_rad_s, 1e-9);
        detail = dA;
        if ~okB
            detail = dB;
        end
        results = record(results, ['dynamics: ' c.name], okA && okB, detail);
    end
end

function results = profileCases(results, fx, tol)
    cfgFx = fx.config;
    inertia = cfgFx.inertia_kg_m2.';
    alpha = cfgFx.max_torque_Nm / inertia(1) * cfgFx.profile_authority;
    omegaMax = cfgFx.momentum_capacity_Nms / inertia(1) ...
        * cfgFx.profile_authority;

    for k = 1:numel(fx.profile)
        c = fx.profile(k);
        p = adcs.slew_profile(c.start.', c.finish.', alpha, omegaMax);
        [okD, dD] = compareVec(p.duration, c.expected_duration_s, 1e-9);
        [okA, dA] = compareVec(p.totalAngle, ...
            c.expected_total_angle_rad, 1e-9);

        ok = okD && okA;
        detail = dD;
        if ~okA
            detail = dA;
        end
        for s = 1:numel(c.samples)
            sample = c.samples(s);
            [qRef, omegaRef] = p.referenceAt(sample.elapsed_s);
            angle = adcs.quat.pointingError(qRef, sample.quaternion.');
            [okQ, dQ] = compareVec(angle, 0, 1e-9);
            [okW, dW] = compareVec(omegaRef, sample.omega_rad_s, 1e-9);
            if ~okQ
                ok = false; detail = sprintf('t=%.3f q: %s', ...
                    sample.elapsed_s, dQ);
            elseif ~okW
                ok = false; detail = sprintf('t=%.3f w: %s', ...
                    sample.elapsed_s, dW);
            end
        end
        results = record(results, ['profile: ' c.name], ok, detail);
    end
end

function results = controllerCases(results, fx, tol)
    cfgFx = fx.config;
    inertia = cfgFx.inertia_kg_m2.';
    wn = cfgFx.natural_frequency_rad_s;
    kp = inertia * wn^2;
    kd = 2 * cfgFx.damping_ratio * wn * inertia;

    for k = 1:numel(fx.controller)
        c = fx.controller(k);
        got = adcs.tracking_torque(c.quaternion.', c.omega_rad_s.', ...
            c.quaternion_reference.', c.omega_reference_rad_s.', kp, kd);
        [ok, d] = compareVec(got, c.expected_torque_Nm, tol);
        results = record(results, ['controller: ' c.name], ok, d);
    end
end

function results = modeCases(results, fx)
    cfg = struct('settleEntryRad', fx.config.settle_entry_rad, ...
                 'maxBodyRateRadS', fx.config.max_body_rate_rad_s);
    for k = 1:numel(fx.mode_chart)
        c = fx.mode_chart(k);
        % The reference's SLEW branch holds until the profile finishes;
        % these fixtures never mark it done.
        profileDone = false;
        got = adcs.mission_mode(c.mode_in, 0, 10, ...
            c.boresight_error_rad, c.body_rate_rad_s, ...
            c.momentum_fraction, logical(c.slew_requested), ...
            profileDone, cfg);
        ok = strcmp(got, c.expected_mode);
        results = record(results, ['mode: ' c.name], ok, ...
            sprintf('got %s, expected %s', got, c.expected_mode));
    end
end

function results = closedLoopCases(results, fx)
    %CLOSEDLOOPCASES Whole-run agreement, coarsely.
    %
    % Step-by-step agreement over thousands of steps would fail on
    % floating-point summation order alone. What has to match is the
    % trajectory's shape and the numbers the study reports, so the
    % tolerance here is 1e-6 rad on attitude rather than 1e-9.
    cfgFx = fx.config;
    inertia = cfgFx.inertia_kg_m2.';
    wn = cfgFx.natural_frequency_rad_s;
    kp = inertia * wn^2;
    kd = 2 * cfgFx.damping_ratio * wn * inertia;
    alpha = cfgFx.max_torque_Nm / inertia(1) * cfgFx.profile_authority;
    omegaMax = cfgFx.momentum_capacity_Nms / inertia(1) ...
        * cfgFx.profile_authority;

    for k = 1:numel(fx.closed_loop)
        c = fx.closed_loop(k);
        p = adcs.slew_profile(c.start.', c.target.', alpha, omegaMax);
        q = c.start.';
        w = [0 0 0];
        h = [0 0 0];
        steps = round(c.duration_s / c.dt);
        log = zeros(steps + 1, 8);
        for index = 0:steps
            t = index * c.dt;
            [qRef, omegaRef] = p.referenceAt(t);
            err = adcs.quat.boresightError(q, c.target.', ...
                cfgFx.boresight_body.');
            log(index + 1, :) = [t q err h];
            tau = adcs.tracking_torque(q, w, qRef, omegaRef, kp, kd);
            [delivered, h] = adcs.wheels(tau, c.dt, h, ...
                cfgFx.max_torque_Nm, cfgFx.momentum_capacity_Nms, [1 1 1]);
            [q, w] = adcs.rigid_body_step(q, w, delivered, h, inertia, c.dt);
        end

        ok = true;
        detail = '';
        for s = 1:numel(c.checkpoints)
            cp = c.checkpoints(s);
            [~, row] = min(abs(log(:, 1) - cp.time_s));
            angle = adcs.quat.pointingError(log(row, 2:5), cp.quaternion.');
            if angle > 1e-6
                ok = false;
                detail = sprintf(['t=%.1f attitude differs by %.3e rad ' ...
                    '(%.4f deg)'], cp.time_s, angle, rad2deg(angle));
                break
            end
            if abs(log(row, 6) - cp.boresight_error_rad) > 1e-6
                ok = false;
                detail = sprintf(['t=%.1f boresight error %.6e, ' ...
                    'expected %.6e'], cp.time_s, log(row, 6), ...
                    cp.boresight_error_rad);
                break
            end
        end
        results = record(results, ['closed loop: ' c.name], ok, detail);
    end
end
